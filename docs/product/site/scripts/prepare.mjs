import { cp, mkdir, readdir, readFile, rm, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import yaml from 'js-yaml'

import { transformDocument } from './transform-document.mjs'

const root = path.dirname(fileURLToPath(import.meta.url))
const site = path.resolve(root, '..')
const contentRoot = process.env.DOCS_CONTENT ?? '/input/content'
const assetsRoot = process.env.DOCS_ASSETS ?? '/input/assets'
const basePath = process.env.NEXT_PUBLIC_BASE_PATH ?? '/sounding'

async function markdownFiles(directory) {
  const entries = await readdir(directory, { withFileTypes: true })
  const files = await Promise.all(
    entries.map(async (entry) => {
      const filename = path.join(directory, entry.name)
      return entry.isDirectory() ? markdownFiles(filename) : [filename]
    }),
  )
  return files.flat().filter((filename) => filename.endsWith('.md'))
}

async function removeGeneratedLayouts(directory) {
  const entries = await readdir(directory, { withFileTypes: true })
  for (const entry of entries) {
    const filename = path.join(directory, entry.name)
    if (entry.isDirectory()) {
      await removeGeneratedLayouts(filename)
    } else if (entry.name === 'layout.tsx' && filename !== path.join(site, 'src', 'app', 'layout.tsx')) {
      const source = await readFile(filename, 'utf8')
      if (source.startsWith('// Generated by scripts/prepare.mjs.')) {
        await rm(filename)
      }
    }
  }
}

function metadataLayout(title, description) {
  return `// Generated by scripts/prepare.mjs. Do not edit.
import { type Metadata } from 'next'

export const metadata: Metadata = {
  title: ${JSON.stringify(title)},
  description: ${JSON.stringify(description)},
}

export default function DocumentationLayout({
  children,
}: {
  children: React.ReactNode
}) {
  return children
}
`
}

function routeFor(relativeDocument) {
  const route = relativeDocument
    .replace(/\\/g, '/')
    .replace(/\.md$/, '')
    .replace(/(^|\/)index$/, '')
  return route ? `/${route}/` : '/'
}

export async function prepare() {
  const documents = await markdownFiles(contentRoot)
  const appRoot = path.join(site, 'src', 'app')

  await removeGeneratedLayouts(appRoot)
  for (const existing of await markdownFiles(appRoot)) {
    await rm(existing)
  }

  for (const document of documents) {
    const relativeDocument = path.relative(contentRoot, document)
    const route = routeFor(relativeDocument)
    const routeDirectory = route === '/' ? appRoot : path.join(appRoot, route)
    const destination = path.join(routeDirectory, 'page.md')
    const source = await readFile(document, 'utf8')
    const transformed = transformDocument(source, {
      relativeDocument: relativeDocument.replace(/\\/g, '/'),
      basePath,
    })
    await mkdir(routeDirectory, { recursive: true })
    await writeFile(destination, transformed)
    if (route !== '/') {
      const frontmatter = source.match(/^---\r?\n([\s\S]*?)\r?\n---(?:\r?\n|$)/)[1]
      const metadata = yaml.load(frontmatter)
      await writeFile(
        path.join(routeDirectory, 'layout.tsx'),
        metadataLayout(metadata.title, metadata.description),
      )
    }
  }

  const publicAssets = path.join(site, 'public', 'assets')
  await rm(publicAssets, { recursive: true, force: true })
  await mkdir(path.dirname(publicAssets), { recursive: true })
  await cp(assetsRoot, publicAssets, { recursive: true })

  console.log(`Prepared ${documents.length} Markdown routes and copied documentation assets.`)
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await prepare()
}
